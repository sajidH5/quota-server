// Writes src/assets.js: the logo and the IBM Plex fonts (assets/) as base64, so the same code
// runs on Cloudflare Workers and Node. Run it after changing a file in assets/: npm run assets
// Fonts: official IBM Plex TrueType releases (github.com/IBM/plex), SIL Open Font License (assets/OFL.txt).
import { readFileSync, writeFileSync } from 'node:fs';

const FILES = {
    logo: 'logo.png',
    sans: 'IBMPlexSans-Regular.ttf',
    sansSemiBold: 'IBMPlexSans-SemiBold.ttf',
    mono: 'IBMPlexMono-Regular.ttf',
    monoMedium: 'IBMPlexMono-Medium.ttf',
};
const lines = Object.entries(FILES).map(([name, file]) => {
    const base64 = readFileSync(new URL(`../assets/${file}`, import.meta.url)).toString('base64');
    return `export const ${name} = '${base64}';`;
});
writeFileSync(new URL('../src/assets.js', import.meta.url),
    `// Generated by scripts/build-assets.js from assets/. Do not edit.\n${lines.join('\n')}\n`);
console.log('src/assets.js written');
